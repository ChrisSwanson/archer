// AJV's official standalone compiler: the frozen schema is compiled at build time,
// so the browser validates without runtime Function/eval or an AJV compiler.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
const schema = JSON.parse(readFileSync(new URL("../../schema/diagram-envelope.schema.json", import.meta.url), "utf8"));
const target = new URL("../src/protocol/envelope-validator.generated.cjs", import.meta.url);
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true } });
const code =
  "// Generated by node ui/scripts/generate-validator.mjs; do not edit.\n" +
  standaloneCode(ajv, ajv.compile(schema)) +
  "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== code) {
    throw new Error(`Stale validator: run node ui/scripts/generate-validator.mjs (${fileURLToPath(target)})`);
  }
} else writeFileSync(target, code);
